'use strict';

// Apps Script parses every .gs file on each web app request. StandardsData.gs
// used to bundle STANDARDS_SUBJECTS (~245KB, always needed) together with
// STANDARDS_DATA (elementary/middle/high achievement standards, ~29MB total,
// only needed when an admin runs "성취기준 데이터 설정"). This script splits
// the achievement-standard payload out into one file per school level so the
// common request path stops paying for the ~99% of the bundle it never reads.
//
// Safe to rerun: if StandardsData.gs no longer contains STANDARDS_DATA, it is
// already split and this is a no-op.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'StandardsData.gs');
const HEADER = '// Generated by scripts/build-standards-2015.js. Do not edit by hand.';

const LEVELS = [
  { key: 'elementary', constant: 'STANDARDS_DATA_ELEMENTARY', file: 'StandardsData_elementary.gs' },
  { key: 'middle', constant: 'STANDARDS_DATA_MIDDLE', file: 'StandardsData_middle.gs' },
  { key: 'high', constant: 'STANDARDS_DATA_HIGH', file: 'StandardsData_high.gs' },
];

function split() {
  const source = fs.readFileSync(SOURCE, 'utf8');
  const lines = source.split('\n');
  const subjectsLine = lines.find((line) => line.startsWith('const STANDARDS_SUBJECTS = '));
  if (!subjectsLine) throw new Error('const STANDARDS_SUBJECTS not found in StandardsData.gs');

  const dataLines = Object.fromEntries(
    LEVELS.map(({ key }) => [key, lines.find((line) => line.startsWith(`  ${key}: '`))])
  );
  if (LEVELS.every(({ key }) => !dataLines[key])) {
    console.log('Already split (StandardsData.gs has no STANDARDS_DATA block); nothing to do.');
    return;
  }
  const missing = LEVELS.filter(({ key }) => !dataLines[key]).map(({ key }) => key);
  if (missing.length) throw new Error(`Missing school level data in STANDARDS_DATA: ${missing.join(', ')}`);

  for (const { key, constant, file } of LEVELS) {
    // "  elementary: '[...]'," -> "'[...]'"
    const value = dataLines[key].trim().replace(new RegExp(`^${key}:\\s*`), '').replace(/,$/, '');
    fs.writeFileSync(path.join(ROOT, file), `${HEADER}\nconst ${constant} = ${value};\n`, 'utf8');
  }
  fs.writeFileSync(SOURCE, `${HEADER}\n${subjectsLine}\n`, 'utf8');
  console.log('Split complete.');
}

split();
